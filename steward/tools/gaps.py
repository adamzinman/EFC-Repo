"""Write steward/GAPS.md from type_map.json, AUDIT.md and the project tree. Prints counts only."""
import json, os, re, sys
R = sys.argv[1] if len(sys.argv) > 1 else "."
tm = json.load(open(f"{R}/steward/type_map.json"))
cfg = json.load(open(f"{R}/steward.config.json"))
VIEWS = [f"{R}/{p}/com.inductiveautomation.perspective/views" for p in cfg["projects"]]
audit = open(f"{R}/steward/AUDIT.md").read()
bad_dock = set(re.findall(r"^- (\S+) \[(?:missing|wrong)-dock\]", audit, re.M))

def vfile(path):
    for v in VIEWS:
        f = f"{v}/{path}/view.json"
        if os.path.exists(f):
            return f

def dock_for(item):
    best = max((k for k in cfg["dock_map"] if item.startswith(k)), key=len, default=None)
    return cfg["dock_map"].get(best)

slug = lambda p: p.replace("/", "_")
prev = lambda p: os.path.exists(f"{R}/steward/previews/{slug(p)}.html")
rows, n = [], {"items": 0, "type": 0, "click": 0, "dock": 0, "preview": 0, "new": 0, "gaptype": set()}
for item, t in tm["items"].items():
    f = vfile(item)
    kind = "faceplate" if "/IO/" in item or "/Station/" in item else "template"
    gap = t.startswith("gap:")
    native = t.startswith("native:")
    tname = t[4:] if gap else t
    if gap: n["gaptype"].add(tname)
    txt = open(f).read() if f else ""
    bound = native or (bool(f) and not gap and any(re.search(rf"\b{x}\b", txt) for x in tname.split("|")))
    ex = next((r for k, r in tm.get("click_exempt", {}).items() if item.startswith(k)), None)
    wired = ex is not None or "efc.ui.openDynamic" in txt  # embedded-view strategy (decision 24)
    bound = bound or (ex is not None and "{0}/" in txt)   # exempt panels bind members through tagPath only
    d = dock_for(item)
    dexist = vfile(tm["docks"][d]) is not None
    p = prev(item)
    if not f: kind += " (NEW)"; n["new"] += 1
    rows.append(f"| {item} | {kind} | {('native (x80 device DDT)' if native else 'yes') if bound else ('GAP ' + tname if gap else 'no -> ' + tname)} | {('n/a: ' + ex) if ex else ('yes' if wired else 'no')} | {d}: {'yes' if dexist else 'no'} | {'yes' if p else 'no'} |")
    n["items"] += 1; n["type"] += not bound; n["click"] += not wired; n["dock"] += not dexist; n["preview"] += not p
for d, path in tm["docks"].items():
    e, p = vfile(path) is not None, prev(path)
    rows.append(f"| {path} | dock{'' if e else ' (NEW)'} | n/a | n/a | {d}: {'yes' if e else 'no'} | {'yes' if p else 'no'} |")
    n["preview"] += not p; n["dock"] += 0
docks_missing = sum(vfile(p) is None for p in tm["docks"].values())
open(f"{R}/steward/GAPS.md", "w").write(
    "# Gap report\n\nGenerated by `steward/tools/gaps.py` from `steward/type_map.json`. Interaction: click on the symbol calls `efc.ui.openDynamic`, which switches the screen's dynamic-window region (embedded view, decision 24).\n\n"
    "| item | kind | T_ type bound? | click wired? | dock exists? | preview exists? |\n|---|---|---|---|---|---|\n" + "\n".join(rows) + "\n")
print(f"items {n['items']} (new {n['new']}) | no T_ binding {n['type']} | click not wired {n['click']} | docks missing {docks_missing} of {len(tm['docks'])} | previews missing {n['preview']} | missing T_ types: {', '.join(sorted(n['gaptype']))}")
