def esc(s):
    """Escape plain text for LaTeX."""
    rep = {
        "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
        "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}",
        "^": r"\textasciicircum{}", "<": r"\textless{}", ">": r"\textgreater{}",
    }
    return "".join(rep.get(c, c) for c in s)


def md(s):
    """Convert inline markdown (code, bold) to LaTeX."""
    out_parts = []
    for i, part in enumerate(re.split(r"`([^`]*)`", s)):
        if i % 2:
            out_parts.append(r"\texttt{" + esc(part) + "}")
        else:
            t = esc(part)
            t = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", t)
            t = t.replace(" - ", " --- ").replace("/", "/\\allowbreak{}")
            out_parts.append(t)
    return "".join(out_parts)


def table_rows(start):
    """Return rows (list of cell lists) of the markdown table starting at index start."""
    rows = []
    i = start
    while i < len(lines) and lines[i].startswith("|"):
        cells = [c.strip() for c in lines[i].strip().strip("|").split("|")]
        if not set("".join(cells)) <= set("-: "):
            rows.append(cells)
        i += 1
    return rows, i


def find(prefix, after=0):
    for i in range(after, len(lines)):
        if lines[i].startswith(prefix):
            return i
    raise KeyError(prefix)


def first_table_after(idx):
    i = idx
    while not lines[i].startswith("|"):
        i += 1
    return table_rows(i)[0]


def longtable(colspec, header, rows, caption, label, small=True):
    n = len(header)
    h = " & ".join(r"\textbf{" + c + "}" for c in header)
    o = []
    if small:
        o.append(r"\begin{small}")
    o.append(r"\begin{longtable}{@{}" + colspec + "@{}}")
    o.append(r"\caption{" + caption + r"}\label{" + label + r"} \\")
    o.append(r"\toprule")
    o.append(r"\rowcolor{tblhead}" + h + r" \\")
    o.append(r"\midrule")
    o.append(r"\endfirsthead")
    o.append(r"\multicolumn{" + str(n) + r"}{@{}l}{\small\textit{Table \thetable{} continued}} \\")
    o.append(r"\toprule")
    o.append(r"\rowcolor{tblhead}" + h + r" \\")
    o.append(r"\midrule")
    o.append(r"\endhead")
    for r in rows:
        o.append(" & ".join(r) + r" \\")
    o.append(r"\bottomrule")
    o.append(r"\end{longtable}")
    if small:
        o.append(r"\end{small}")
    return "\n".join(o)


