"""
PCLib LaTeX generator - writes the data-type appendix for the EFC Controls Standard.

Produces:
  tex/pclib-data-types.tex   appendix body for appendices/ in the Controls Standard (uses \\note, \\newmark, tblhead)
  tex/preview_pclib.tex    standalone wrapper that defines those macros, for compiling on its own

Usage:  python gen_tex.py      (reads the type definitions from gen_pclib.py)
"""
import os
import re

import gen_pclib as lib

PREFIX = "T_"
HERE = os.path.dirname(os.path.abspath(__file__))

_ESC = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_",
        "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
        "<": r"\textless{}", ">": r"\textgreater{}"}


def tx(s):
    """Escape plain text for LaTeX."""
    s = "".join(_ESC.get(c, c) for c in s)
    return s.replace(r"-\textgreater{}", r"$\rightarrow$").replace("/", r"/\allowbreak{}")


def tt(s):
    return r"\texttt{" + tx(s) + "}"


def code_spans(s):
    """Escape text, rendering `backtick` spans as \\texttt and **bold** as \\textbf."""
    out = []
    for i, part in enumerate(s.split("`")):
        if i % 2:
            out.append(tt(part))
        else:
            part = tx(part)
            part = re.sub(r"\*\*(.+?)\*\*", r"\\textbf{\1}", part)
            out.append(part)
    return "".join(out)


def longtable(cols, head, rows, size=None):
    L = []
    if size:
        L.append("{" + size)
    L.append(r"\begin{longtable}{@{}" + "".join(f">{{\\raggedright\\arraybackslash}}p{{{w}}}" for w in cols) + "@{}}")
    L.append(r"\toprule")
    L.append(r"\rowcolor{tblhead}" + " & ".join(rf"\textbf{{{h}}}" for h in head) + r" \\")
    L.append(r"\midrule")
    L.append(r"\endhead")
    for r in rows:
        L.append(" & ".join(r) + r" \\")
    L.append(r"\bottomrule")
    L.append(r"\end{longtable}")
    if size:
        L.append("}")
    return L


def enum_rows(text):
    """'0=Good 1=Failure (F) ...' -> [(value, meaning), ...]"""
    parts = re.split(r"\s+(?=-?\d+=)", text.strip())
    return [p.split("=", 1) for p in parts]


DFB_STATUS = [
    ("FB_AlmCore", "ISA-18.2 / IEC 62682 alarm state machine with plain parameters", "Built, not compiled"),
    ("FB_Alarm", "Maps a T_Alarm onto FB_AlmCore", "Built, not compiled"),
    ("FB_AlmLim", "High/low limit with deadband, maps a T_AlmLim onto FB_AlmCore", "Built, not compiled"),
    ("FB_AI", "Analog input processing for a T_AI", "Built, not compiled"),
    ("T_DI, T_Motor, T_VFD, T_DValve, T_CValve, T_PID, T_Intlk, T_Phase, then equipment modules",
     "One DFB per type, reusing FB_AlmCore / FB_Alarm / FB_AlmLim", "Planned, in this order"),
]


def build(types, d):
    meta = {n: lib.META[n[len(PREFIX):]] for n, *_ in types}
    nmem = sum(len(t[2]) for t in types)
    L = []
    w = L.append
    w("% ============================================================")
    w("% Appendix: Standard PLC / SCADA Data Types (PCLib)")
    w("% GENERATED by PCLib/gen_tex.py from gen_pclib.py - do not hand-edit.")
    w("% Insert into controls_standard.tex before \\end{document}:")
    w("%     \\appendix")
    w("%     \\input{appendices/pclib-data-types}")
    w("% Uses preamble.tex macros: \\note, \\newmark, tblhead.")
    w("% Needs packages: longtable, booktabs, xcolor[table], enumitem.")
    w("% ============================================================")
    w("")
    w(r"\chapter{Standard PLC and SCADA Data Types (PCLib) \newmark}")
    w(r"\label{app:pclib}")
    w("")
    w(f"This appendix lists the company's standard equipment data types, the Process Control Library "
      f"(PCLib) version {lib.LIB_VERSION}. It holds {len(types)} Derived Data Types (DDTs) for "
      r"EcoStruxure Control Expert Classic V16.2 (M340/M580) with matching Ignition 8.1 Perspective UDTs. "
      f"Together they have {nmem} top-level members. Every type is built for HMI faceplates and aligned with "
      r"ISA-88, ISA-18.2, ISA-101, NAMUR NE107 and the other standards in Section~\ref{app:pclib:stds}.")
    w("")
    w(r"\textbf{Source of truth:} the generator \texttt{PCLib/gen\_pclib.py} in the EFC Repo. It produces "
      r"the Control Expert import file (\texttt{export/\allowbreak PCLib\_\allowbreak CE\_\allowbreak V16.2.xdd}), the Ignition import file "
      r"(\texttt{export/\allowbreak PCLib\_\allowbreak Ignition81.json}), the member list (\texttt{PCLib\_Members.csv}) and this "
      r"appendix. Change a type in the generator and re-run it; never edit the outputs by hand.")
    w("")
    w(r"\note{Nothing in PCLib has been imported or compiled yet in Control Expert V16.2 or Ignition 8.1. "
      r"Validate the import files on the first project before they are released.}")
    w("")
    w(r"\note{Decide how PCLib relates to the existing types referenced in this standard "
      r"(DDT\_Process\_Value, DDT\_Device, DDT\_AI\_Alarm, DDT\_Interlock): replace, map, or keep both. "
      r"PCLib uses the \texttt{T\_} prefix; the generator can emit \texttt{DDT\_} instead "
      r"(\texttt{--prefix DDT\_}).}")
    w("")

    # ---- Catalogue ----
    w(r"\section{Type Catalogue}")
    w(r"\label{app:pclib:catalogue}")
    w(r"Members are counted at the top level: a nested type (for example \texttt{Mode} or \texttt{Alm\_HH}) "
      r"counts as one. \textit{Depends on} lists direct dependencies only; import order is handled by "
      r"the combined import file.")
    for g, title in lib.GROUP_TITLES.items():
        rows = []
        for name, comment, members, group in types:
            if group != g:
                continue
            direct = sorted({mt.split(" OF ")[-1] for _, mt, _, _ in members
                             if mt.split(" OF ")[-1] in d})
            role, mtp, _ = meta[name]
            rows.append([tt(name), tx(comment), tx(role), tx(mtp), str(len(members)),
                         ", ".join(tt(x) for x in direct) or "---"])
        w(rf"\subsection*{{{title}}}")
        L.extend(longtable(["2.3cm", "4.3cm", "2.3cm", "2.4cm", "1.1cm", "2.0cm"],
                           ["Type", "Purpose", "ISA-88 role", "MTP", "Mem.", "Depends on"],
                           rows, size=r"\small"))
    w(r"\note{\texttt{T\_ESD}, \texttt{T\_Intlk} and \texttt{T\_GasDet} are basic process control (BPCS) "
      r"functions only. Safety Instrumented Functions with a SIL target run in a certified safety "
      r"controller and follow IEC 61511.}")
    w("")

    # ---- Conventions ----
    w(r"\section{Naming Conventions}")
    w(r"\label{app:pclib:conv}")
    prefixes = [
        ("Inp_", "Field or upstream input", "I/O mapping or upstream logic"),
        ("Cfg_", "Configuration and tuning", "Engineer (HMI with access control)"),
        ("Cmd_", "Operator command. Booleans are one-shot: the DFB clears them after acting", "HMI"),
        ("Prog_", "Command from the ISA-88 owner (phase, equipment module, batch server)", "Owner logic"),
        ("Prm_ / Rpt_", "ISA-88 recipe parameters / report values", "Batch server / phase logic"),
        ("Out_", "Output to field or downstream logic", "Equipment logic"),
        ("Sts_", "Status", "Equipment logic"),
        ("Val_", "Calculated value", "Equipment logic"),
        ("Alm_", "Alarm object (T_Alarm or T_AlmLim)", "Equipment logic sets Inp_Cond"),
        ("Sim_", "Simulation", "Engineer"),
    ]
    L.extend(longtable(["2.4cm", "7.4cm", "4.6cm"], ["Prefix", "Meaning", "Written by"],
                       [[tt(p), tx(m), tx(b)] for p, m, b in prefixes]))
    w(r"\begin{itemize}[itemsep=2pt]")
    for item in [
        "Booleans ending in `OK` are **TRUE = healthy**, so a broken wire or lost signal reads as unhealthy. "
        "Other `Inp_` booleans are TRUE when the condition is present.",
        "An **interlock** (`Inp_IntlkOK`) trips running equipment. A **permissive** (`Inp_PermOK`) only blocks a start.",
        "Every equipment type starts with `Cfg_Tag` (STRING[20], the ISA-5.1 tag) and `Cfg_Desc` (STRING[40]).",
        "Field-device control modules carry `Sts_NE107`. Smart devices (HART or fieldbus) also carry `Inp_NE107`.",
        "Shelving and bypasses are always time-limited (`Cfg_MaxShelf`, `Cfg_BypassMax`, `Cfg_MOSMax`).",
        "Limit alarms (`T_AlmLim`) default to disabled and are enabled once the limit is rationalised. "
        "Discrete alarms (`T_Alarm`) default to enabled.",
        "Analog raw range defaults to 0--10000 (M340/M580 4--20\\,mA). `T_AI` bad limits follow NE43: "
        "--2.5\\,% and 106.25\\,% of span.",
        "Identifiers are at most 32 characters and avoid IEC / Control Expert reserved words. Comments are ASCII only.",
        "In Ignition only `Cfg_`, `Cmd_`, `Sim_` and `Prm_` tags are writable. Everything else is read-only "
        "(ISA-101: the HMI never writes PLC status).",
    ]:
        w(r"  \item " + code_spans(item).replace(r"\textbackslash{},", r"\,").replace(r"\textbackslash{}", "\\"))
    w(r"\end{itemize}")
    w("")

    # ---- Enumerations ----
    w(r"\section{Enumerated Values}")
    w(r"\label{app:pclib:enums}")
    enums = [
        ("Mode (T\\_Mode.Sts\\_Mode)", "0=OOS (MTP Offline) 1=Maintenance 2=Manual (MTP Operator) 3=Automatic (MTP Automatic)"),
        ("Alarm state (Sts\\_State, ISA-18.2 A--H)", lib.ALARM_STATES),
        ("Alarm priority (Cfg\\_Priority)", "1=Emergency 2=High 3=Medium 4=Low"),
        ("Alarm class (Cfg\\_Class)", "0=General 1=Safety 2=Environmental 3=Quality 4=Asset"),
        ("NAMUR NE107 (Sts\\_NE107)", lib.NE107_TXT),
        ("Phase state (T\\_Phase.Sts\\_State, ISA-88 Part 1)", lib.PHASE_STATES),
        ("Phase command (Prog\\_Cmd, Sts\\_CmdMask bit n)", lib.PHASE_CMDS),
        ("Phase / unit mode (Sts\\_Mode)", "1=Manual 2=Semi-automatic 3=Automatic"),
        ("Equipment state (Sts\\_EqState, T\\_Unit / T\\_Tank)", lib.EQSTATE),
    ]
    for title, text in enums:
        w(rf"\subsection*{{{title}}}")
        L.extend(longtable(["1.4cm", "13.0cm"], ["Value", "Meaning"],
                           [[v, tx(m)] for v, m in enum_rows(text)], size=r"\small"))
    w("")

    # ---- Standards ----
    w(r"\section{Standards Alignment}")
    w(r"\label{app:pclib:stds}")
    w(r"Alignment is by design, not third-party certification. Apart from MTP, the standards define models "
      r"and behaviour rather than PLC data layouts; PCLib carries the data each model needs.")
    L.extend(longtable(["3.2cm", "3.4cm", "7.8cm"], ["Standard", "Scope", "How PCLib applies it"],
                       [[tx(s), tx(sc), code_spans(h.format(p=PREFIX))] for s, sc, h in lib.STANDARDS],
                       size=r"\small"))
    w(r"\note{The standards text was applied from general knowledge (most are paywalled). "
      r"Check the alignment claims against licensed copies before release.}")
    w("")

    # ---- DFBs ----
    w(r"\section{Function Blocks}")
    w(r"\label{app:pclib:dfb}")
    w(r"Data types carry no behaviour; each is paired with an IEC 61131-3 Structured Text DFB generated by "
      r"\texttt{PCLib/gen\_dfb.py}. DFBs take the whole DDT as one \texttt{IN\_OUT} parameter, e.g.\ "
      r"\texttt{fbFT101(AI := FT101);}, and use no located or global variables.")
    L.extend(longtable(["4.6cm", "6.6cm", "3.2cm"], ["DFB", "Function", "Status"],
                       [[tx(a) if "," in a else tt(a), tx(b), tx(c)] for a, b, c in DFB_STATUS],
                       size=r"\small"))
    w("")

    # ---- Member reference ----
    w(r"\section{Member Reference}")
    w(r"\label{app:pclib:members}")
    w(r"Every member of every type, in declaration order. \textit{Init} is the initial value when it "
      r"differs from the IEC default (FALSE, 0, empty).")
    for g, title in lib.GROUP_TITLES.items():
        w(rf"\subsection{{{title}}}")
        for name, comment, members, group in types:
            if group != g:
                continue
            role, mtp, stds = meta[name]
            w(rf"\subsubsection*{{{tx(name)}}}")
            w(rf"\label{{app:pclib:{name.lower().replace('_', '')}}}")
            w(tx(comment) + ".")
            w("")
            w(r"{\small\textbf{ISA-88 role:} " + tx(role) + r" \quad \textbf{MTP:} " + tx(mtp) +
              r" \quad \textbf{Standards:} " + tx(", ".join(stds)) + "}")
            rows = []
            for mn, mt, mc, init in members:
                rows.append([tt(mn), tt(mt), tt(init) if init else "", tx(mc)])
            L.extend(longtable(["3.4cm", "3.3cm", "1.3cm", "6.4cm"],
                               ["Member", "Type", "Init", "Description"], rows, size=r"\footnotesize"))
    w("")
    w(r"\section{Sources}")
    w(r"\begin{itemize}[itemsep=1pt]")
    for s in [
        "ANSI/ISA-88.00.01 (IEC 61512-1) Batch control, Part 1: Models and terminology",
        "ANSI/ISA-18.2 (IEC 62682) Management of alarm systems for the process industries",
        "ANSI/ISA-101.01 Human machine interfaces for process automation systems",
        "ANSI/ISA-5.1 Instrumentation symbols and identification",
        "ANSI/ISA-84.00.01 (IEC 61511) Functional safety: safety instrumented systems for the process industry sector",
        "ANSI/ISA-95 (IEC 62264) Enterprise-control system integration",
        "IEC 61131-3 Programmable controllers, Part 3: Programming languages",
        "NAMUR NE107 Self-monitoring and diagnosis of field devices; NAMUR NE43 Standardization of the signal level "
        "for the failure information of digital transmitters",
        "VDI/VDE/NAMUR 2658-4 Automation engineering of modular systems in the process industry (MTP)",
    ]:
        w(r"  \item " + tx(s))
    w(r"\end{itemize}")
    return "\n".join(L) + "\n"


