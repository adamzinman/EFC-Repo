def main():
    types = lib.resolve(lib.TYPES, PREFIX, True)
    d = lib.deps(types)
    out = os.path.join(HERE, "tex")
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "pclib-data-types.tex"), "w", encoding="utf-8") as f:
        f.write(build(types, d))
    with open(os.path.join(out, "preview_pclib.tex"), "w", encoding="utf-8") as f:
        f.write(PREVIEW)
    print(f"{len(types)} types -> tex/pclib-data-types.tex, tex/preview_pclib.tex")


if __name__ == "__main__":
    main()
