# -*- coding: utf-8 -*-
"""Build library_types.py from the EFCLib v1 .xdd files in types/xdd/.

    python3 tools/xsyimport/build_library.py

Each T_* DDT in types/xdd/ becomes a confirmed library layout (the .xdd files are generated by
types/gen_pclib.py, so the member list is the source of truth). PCLib_All.xdd is skipped because it
repeats every type. Re-run after changing the generator.
"""
import glob
import os
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
XDD_DIR = os.path.join(HERE, "..", "..", "types", "xdd")
OUT = os.path.join(HERE, "library_types.py")


def _comment(el):
    c = el.find("comment")
    return (c.text or "").strip() if c is not None and c.text else ""


def load_xdd(path):
    """-> {DDT name: [(member, typeName, comment)]} from one DDTExchangeFile."""
    out = {}
    for src in ET.parse(path).getroot().findall("DDTSource"):
        st = src.find("structure")
        mem = []
        for v in (st.findall("variables") if st is not None else []):
            mem.append((v.get("name"), (v.get("typeName") or "").strip(), _comment(v)))
        out[src.get("DDTName")] = mem
    return out


def build():
    entries = {}
    for path in sorted(glob.glob(os.path.join(XDD_DIR, "T_*.xdd"))):
        rel = os.path.relpath(path, os.path.join(HERE, "..", ".."))
        for name, members in load_xdd(path).items():
            if name in entries:
                raise SystemExit("duplicate type %s in %s" % (name, rel))
            entries[name] = {"confidence": "confirmed", "source": rel, "members": members}
    lines = [
        "# -*- coding: utf-8 -*-",
        '"""EFCLib v1 type layouts, generated by build_library.py from types/xdd/. Do not edit by hand."""',
        "",
        "LIBRARY_TYPES = {",
    ]
    for name in sorted(entries):
        e = entries[name]
        lines.append("    %r: {" % name)
        lines.append("        'confidence': %r," % e["confidence"])
        lines.append("        'source': %r," % e["source"])
        lines.append("        'members': [")
        for m in e["members"]:
            lines.append("            %r," % (m,))
        lines.append("        ],")
        lines.append("    },")
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return len(entries), sum(len(e["members"]) for e in entries.values())


if __name__ == "__main__":
    n, m = build()
    print("wrote %s: %d types, %d members" % (OUT, n, m))
